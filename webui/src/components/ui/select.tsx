function decorateSelectChildren(children: React.ReactNode): {
  decoratedChildren: React.ReactNode;
  itemCount: number;
} {
  const decorateNodes = (
    nodes: React.ReactNode,
    startIndex: number,
  ): [React.ReactNode, number] => {
    let currentIndex = startIndex;

    const mappedNodes = React.Children.map(nodes, (child) => {
      if (!React.isValidElement(child)) {
        return child;
      }

      const element = child as React.ReactElement<{
        children?: React.ReactNode;
        style?: React.CSSProperties;
      }>;
      const childDisplayName = (element.type as { displayName?: string })
        .displayName;

      if (childDisplayName === SelectItem.displayName) {
        const itemIndex = currentIndex;
        currentIndex += 1;

        return React.cloneElement(element, {
          style: {
            ...(element.props.style || {}),
            ["--select-item-index" as string]: itemIndex,
          } as React.CSSProperties,
        });
      }

      if (!element.props.children) {
        return child;
      }

      const [decoratedChildren, nextIndex] = decorateNodes(
        element.props.children,
        currentIndex,
      );
      currentIndex = nextIndex;

      return React.cloneElement(element, undefined, decoratedChildren);
    });

    return [mappedNodes, currentIndex];
  };

  const [decoratedChildren, itemCount] = decorateNodes(children, 0);

  return { decoratedChildren, itemCount };
}

const SelectContent = React.forwardRef<
  React.ElementRef<typeof SelectPrimitive.Content>,
  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Content>
>(
  (
    {
      className,
      children,
      position = "popper",
      onPointerDownOutside,
      ...props
    },
    ref,
  ) => {
    const { decoratedChildren, itemCount } = decorateSelectChildren(children);

    return (
      <SelectPrimitive.Portal>
        <SelectPrimitive.Content
          ref={ref}
          className={cn(
            "select-content-motion floating-glass-surface relative z-[140] max-h-96 min-w-[8rem] overflow-hidden rounded-md border text-popover-foreground shadow-md data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:duration-220 data-[state=open]:duration-200 data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2",
            position === "popper" &&
              "data-[side=bottom]:translate-y-1 data-[side=left]:-translate-x-1 data-[side=right]:translate-x-1 data-[side=top]:-translate-y-1",
            className,
          )}
          onPointerDownOutside={(event) => {
            onPointerDownOutside?.(event);
            if (!event.defaultPrevented) {
              preserveOverlayOnTitleBarInteraction(event);
            }
          }}
          position={position}
          {...props}
        >
          <SelectScrollUpButton />
          <SelectPrimitive.Viewport
            className={cn(
              "select-viewport-stagger p-1",
              position === "popper" &&
                "h-[var(--radix-select-trigger-height)] w-full min-w-[var(--radix-select-trigger-width)]",
            )}
            style={{ ["--select-item-count" as string]: itemCount }}
          >
            {decoratedChildren}
          </SelectPrimitive.Viewport>
          <SelectScrollDownButton />
        </SelectPrimitive.Content>
      </SelectPrimitive.Portal>
    );
  },
);
SelectContent.displayName = SelectPrimitive.Content.displayName;

